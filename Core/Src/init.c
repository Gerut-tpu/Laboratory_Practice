    SET_BIT(GPIOD->MODER, GPIO_MODER_MODE1_0);     // PD1: Output mode [file:21]
    CLEAR_BIT(GPIOD->OTYPER, GPIO_OTYPER_OT1);     // PD1: Push‑Pull [file:21]
    SET_BIT(GPIOD->OSPEEDR, GPIO_OSPEEDER_OSPEEDR1_0); // PD1: medium speed [file:21]
