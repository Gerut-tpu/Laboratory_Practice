    CLEAR_BIT(GPIOB->PUPDR, GPIO_PUPDR_PUPDR7_0 | GPIO_PUPDR_PUPDR7_1); // PB7: no 

    SET_BIT(GPIOB->MODER, GPIO_MODER_MODE14_0);     // PB14: Output mode [file:21]
    CLEAR_BIT(GPIOB->OTYPER, GPIO_OTYPER_OT14);     // PB14: Push‑Pull [file:21]
    SET_BIT(GPIOB->OSPEEDR, GPIO_OSPEEDER_OSPEEDR14_0); // PB14: medium speed [file:21]
    CLEAR_BIT(GPIOB->PUPDR, GPIO_PUPDR_PUPDR14_0 | GPIO_PUPDR_PUPDR14_1); // PB14: no 

