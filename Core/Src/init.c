    SET_BIT(GPIOB->MODER, GPIO_MODER_MODE7_0);     // PB7: Output mode [file:21]
    CLEAR_BIT(GPIOB->OTYPER, GPIO_OTYPER_OT7);     // PB7: Push‑Pull [file:21]
